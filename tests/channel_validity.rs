use uv_k5_rust_firmware::channel_validity::{ChannelAttributes, is_valid_channel};

struct Case {
    name: &'static str,
    channel: u16,
    band: u8,
    scan_list_1: bool,
    scan_list_2: bool,
    check_scan_list: bool,
    scan_list: u8,
    priority_channel_1: u8,
    priority_channel_2: u8,
    expected: bool,
}

#[test]
fn matches_approved_pinned_channel_vectors() {
    let cases = [
        Case {
            name: "first_memory_valid",
            channel: 0,
            band: 0,
            scan_list_1: false,
            scan_list_2: false,
            check_scan_list: false,
            scan_list: 0,
            priority_channel_1: 0,
            priority_channel_2: 0,
            expected: true,
        },
        Case {
            name: "last_memory_valid",
            channel: 199,
            band: 6,
            scan_list_1: false,
            scan_list_2: false,
            check_scan_list: false,
            scan_list: 0,
            priority_channel_1: 0,
            priority_channel_2: 0,
            expected: true,
        },
        Case {
            name: "first_frequency_invalid",
            channel: 200,
            band: 0,
            scan_list_1: false,
            scan_list_2: false,
            check_scan_list: false,
            scan_list: 0,
            priority_channel_1: 0,
            priority_channel_2: 0,
            expected: false,
        },
        Case {
            name: "last_noaa_invalid",
            channel: 216,
            band: 0,
            scan_list_1: false,
            scan_list_2: false,
            check_scan_list: false,
            scan_list: 0,
            priority_channel_1: 0,
            priority_channel_2: 0,
            expected: false,
        },
        Case {
            name: "uint16_max_invalid",
            channel: u16::MAX,
            band: 0,
            scan_list_1: false,
            scan_list_2: false,
            check_scan_list: false,
            scan_list: 0,
            priority_channel_1: 0,
            priority_channel_2: 0,
            expected: false,
        },
        Case {
            name: "invalid_band",
            channel: 199,
            band: 15,
            scan_list_1: false,
            scan_list_2: false,
            check_scan_list: false,
            scan_list: 0,
            priority_channel_1: 0,
            priority_channel_2: 0,
            expected: false,
        },
        Case {
            name: "not_in_scanlist",
            channel: 1,
            band: 0,
            scan_list_1: false,
            scan_list_2: false,
            check_scan_list: true,
            scan_list: 0,
            priority_channel_1: 10,
            priority_channel_2: 11,
            expected: false,
        },
        Case {
            name: "scanlist_member",
            channel: 2,
            band: 0,
            scan_list_1: true,
            scan_list_2: false,
            check_scan_list: true,
            scan_list: 0,
            priority_channel_1: 10,
            priority_channel_2: 11,
            expected: true,
        },
        Case {
            name: "priority_channel_excluded",
            channel: 3,
            band: 0,
            scan_list_1: true,
            scan_list_2: false,
            check_scan_list: true,
            scan_list: 0,
            priority_channel_1: 3,
            priority_channel_2: 11,
            expected: false,
        },
        Case {
            name: "unsupported_scanlist_ignored",
            channel: 4,
            band: 0,
            scan_list_1: false,
            scan_list_2: false,
            check_scan_list: true,
            scan_list: 2,
            priority_channel_1: 10,
            priority_channel_2: 11,
            expected: true,
        },
        Case {
            name: "scanlist2_member",
            channel: 5,
            band: 0,
            scan_list_1: false,
            scan_list_2: true,
            check_scan_list: true,
            scan_list: 1,
            priority_channel_1: 10,
            priority_channel_2: 11,
            expected: true,
        },
        Case {
            name: "scanlist2_priority_excluded",
            channel: 6,
            band: 0,
            scan_list_1: false,
            scan_list_2: true,
            check_scan_list: true,
            scan_list: 1,
            priority_channel_1: 10,
            priority_channel_2: 6,
            expected: false,
        },
    ];

    for case in cases {
        assert_eq!(
            is_valid_channel(
                case.channel,
                ChannelAttributes {
                    band: case.band,
                    scan_list_1: case.scan_list_1,
                    scan_list_2: case.scan_list_2,
                },
                case.check_scan_list,
                case.scan_list,
                case.priority_channel_1,
                case.priority_channel_2,
            ),
            case.expected,
            "{}",
            case.name
        );
    }
}
